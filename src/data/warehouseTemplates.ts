import type {
  ABCClass,
  SKUItem,
  TemplateCategory,
  WarehouseConfig,
  WarehouseTemplate,
} from '../types/warehouse';

type CompactSkuTuple = [
  code: string,
  name: string,
  abc: ABCClass,
  picks: number,
  l: number,
  w: number,
  h: number,
  kg: number,
  qty: number,
  fragile: boolean,
  color: string,
];

function makeSkus(prefix: string, items: CompactSkuTuple[]): SKUItem[] {
  return items.map(([code, name, abc, picks, l, w, h, kg, qty, fragile, color], idx) => ({
    id: `${prefix}-s${idx + 1}`,
    skuCode: code,
    name,
    category: prefix,
    abcClass: abc,
    dailyPicks: picks,
    lengthCm: l,
    widthCm: w,
    heightCm: h,
    weightKg: kg,
    quantity: qty,
    fragile,
    color,
  }));
}

function makeProConfig(
  aisles: number,
  bays: number,
  levels: number,
  opts: Partial<WarehouseConfig> = {}
): WarehouseConfig {
  return {
    aisles,
    baysPerAisle: bays,
    levels,
    aisleSpacingM: opts.aisleSpacingM ?? 3.4,
    baySpacingM: opts.baySpacingM ?? 1.45,
    binLengthCm: opts.binLengthCm ?? 120,
    binWidthCm: opts.binWidthCm ?? 90,
    binHeightCm: opts.binHeightCm ?? 70,
    equipmentMode: opts.equipmentMode ?? 'reach_truck',
    goldenZoneMinM: 0.8,
    goldenZoneMaxM: 1.65,
    allowRotationAndCoPack: true,
    mapTag: opts.mapTag ?? `${aisles}×${bays}×${levels} · Pro`,
    ...opts,
  };
}

